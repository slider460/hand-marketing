def sh(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit('✗ ' + ' '.join(str(c) for c in cmd) + '\n' + r.stderr[-800:])


def fetch(url):
    req = urllib.request.Request(url, headers={'User-Agent': UA})
    return urllib.request.urlopen(req).read()


def webp(path):
    """Тот же cwebp с теми же ключами, что и в scripts/gen-webp.sh."""
    dst = path + '.webp'
    sh(['cwebp', '-quiet', '-q', '82', '-m', '6', '-sharp_yuv',
        '-metadata', 'none', path, '-o', dst])
    if os.path.getsize(dst) >= os.path.getsize(path):
        os.remove(dst)


def save(path, img, quality=88):
    cv2.imwrite(path, img, [cv2.IMWRITE_JPEG_QUALITY, quality])
    webp(path)


def fonts():
    os.makedirs(FILES, exist_ok=True)
    css = fetch(GF).decode('utf-8')
    blocks = re.findall(r'/\*\s*([a-z-]+)\s*\*/\s*(@font-face\s*\{.*?\})', css, re.S)
    out, n = [], 0
    for subset, block in blocks:
        if subset not in KEEP_SUBSETS:
            continue
        fam = re.search(r"font-family:\s*'([^']+)'", block).group(1)
        wght = re.search(r'font-weight:\s*(\d+)', block).group(1)
        ital = 'italic' in re.search(r'font-style:\s*(\w+)', block).group(1)
        name = (f'{fam.lower().replace(" ", "-")}-{wght}'
                f'{"-italic" if ital else ""}-{subset}.woff2')
        url = re.search(r'url\((https://[^)]+)\)', block).group(1)
        path = os.path.join(FILES, name)
        if not os.path.exists(path):
            open(path, 'wb').write(fetch(url))
            n += 1
        out.append(block.replace(url, f'files/{name}'))
    head = ('/* Piazzolla + Martian Mono, self-host для /video/eaton/.\n'
            '   Сгенерировано scripts/video-eaton-assets.py, руками не править. */\n')
    open(os.path.join(FONTS, 'piazzolla-martian.css'), 'w', encoding='utf-8').write(
        head + '\n'.join(out) + '\n')
    print(f'✓ шрифты: {len(out)} @font-face, скачано файлов {n}')


def cuts():
    """Границы склеек с обеих сторон ролика."""
    dur = duration()
    pts = sorted(set([0.0] + AUTO_CUTS + EXTRA_CUTS + [dur]))
    segs = [(pts[i], pts[i + 1]) for i in range(len(pts) - 1)
            if pts[i + 1] - pts[i] > 0.35]
    return segs


def duration():
    r = subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration',
                        '-of', 'csv=p=0', SRC], capture_output=True, text=True, check=True)
    return round(float(r.stdout.strip()), 2)


