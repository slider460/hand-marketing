def grab(name, sec, crop, width, q):
    vf = []
    if crop:
        vf.append('crop=' + crop)
    vf.append(f'scale={width}:-2:flags=lanczos')
    dst = os.path.join(OUT, name + '.jpg')
    subprocess.run(['ffmpeg', '-v', 'error', '-ss', str(sec), '-i', SRC,
                    '-frames:v', '1', '-vf', ','.join(vf), '-q:v', str(q),
                    dst, '-y'], check=True)
    return dst


if __name__ == '__main__':
    os.makedirs(OUT, exist_ok=True)
    total = 0
    for name, sec, crop, width, q in SHOTS:
        p = grab(name, sec, crop, width, q)
        sz = os.path.getsize(p)
        total += sz
        print(f'{name:10s} {sec:7.1f}s  {sz//1024:4d} KB')
    print(f'— всего {total//1024} KB в {OUT.replace(ROOT, "")}')
