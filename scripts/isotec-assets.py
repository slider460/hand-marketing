#!/usr/bin/env python3
"""Кадры для кейса /isotec — режутся прямо из бренд-ролика «Изотек».

Своих фотографий по проекту нет (кейс — видеопродакшн), поэтому вся графика
страницы это кадры самого фильма: вехи хронологии 2012→2024, шесть площадок с
карты, производственные планы и экраны цифровых сервисов. Кроп у карточек
хронологии и городов подобран так, чтобы в кадр попала фотопанель 3D-слайда,
а не подпись — подписи страница набирает текстом.

Тайминги совпадают с TIMELINE/CHAPTERS в scripts/a2/gen_isotec.py: по клику
плеер перематывается ровно на тот эпизод, кадр из которого лежит в карточке.

Запуск: python3 scripts/isotec-assets.py  (нужен ffmpeg)
"""
