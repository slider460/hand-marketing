#!/usr/bin/env python3
"""Кадры для кейса /zubovo — режутся из презентационного фильма технопарка «Зубово».

Своей фотосъёмки по проекту нет (кейс — видеопродакшн), вся графика страницы это
кадры самого фильма: облёты площадки, инфографика инженерных мощностей, карта
логистики, корпуса резидентов, синхроны двух спикеров и рендер АБК.

Секунды совпадают с CHAPTERS и data-seek в scripts/a2/gen_zubovo.py: карточка на
странице показывает ровно тот эпизод, на который перематывает клик по ней.

Запуск: python3 scripts/zubovo-assets.py  (нужен ffmpeg)
"""
import os
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..'))
SRC = os.path.join(ROOT, 'mirror', 'portfolio', 'zubovo', 'brand-video.mp4')
OUT = os.path.join(ROOT, 'mirror', 'images', 'zubovo')

# имя, секунда, crop (w:h:x:y) или None = весь кадр, ширина на выходе, качество
SHOTS = [
    # ── герой и постер плеера ──────────────────────────────────────────────
    ('hero',      41.0, None, 1280, 3),   # трасса и площадка с высоты
    ('poster',    64.0, None, 1280, 3),   # мастер-план: «общая площадь более 70 гектаров»
    ('plan',     172.0, None, 1280, 3),   # финальный облёт с подсвеченным контуром
    # ── регион и логистика ─────────────────────────────────────────────────
    ('reg',       13.0, None, 1000, 4),   # Башкортостан на карте страны
    ('logimap',   33.5, None, 1280, 3),   # аэропорт, ЖД-станция, речной порт, Уфа
    # ── инженерная инфраструктура ──────────────────────────────────────────
    ('eng-2',     50.0, None, 1000, 4),   # энергоцентр: котельная и сети
    # ── земельный баланс ───────────────────────────────────────────────────
    ('land',      77.0, None, 1100, 4),   # раскраска участков по статусу
    ('adv',      157.0, None, 1280, 4),   # чистый облёт для секции «что получает резидент»
    # ── резиденты ──────────────────────────────────────────────────────────
    ('res-1',     96.0, None, 1000, 4),
    ('res-2',    100.0, None, 1000, 4),
    ('res-4',    165.0, None, 1000, 4),
    # ── производственные участки ───────────────────────────────────────────
    ('prod-1',    69.5, None, 1000, 4),   # сварочный пост
    ('prod-2',   108.0, None, 1000, 4),   # склад трубной продукции
    ('prod-3',   112.0, None, 1000, 4),   # оператор испытательного стенда
    ('prod-4',   116.0, None, 1000, 4),   # стенд опрессовки модулей
    # ── синхроны ───────────────────────────────────────────────────────────
    ('sp-1',     124.0, None,  900, 4),   # Роман Зубов
    ('sp-2',     150.0, None,  900, 4),   # Ильдус Самигуллин
    # ── развитие площадки ──────────────────────────────────────────────────
    ('dev-1',    133.0, None, 1000, 4),   # пятна под новые корпуса
    ('dev-2',    137.0, None, 1000, 4),   # бетонные работы в новом корпусе
    ('dev-3',    142.0, None, 1000, 4),   # каркас административно-бытового корпуса
    ('abk',      145.5, None, 1100, 4),   # рендер АБК: 1735 м² офисов, 178 м² залов
]


def grab(name, sec, crop, width, q):
    vf = []
    if crop:
        vf.append('crop=' + crop)
    vf.append(f'scale={width}:-2:flags=lanczos')
    dst = os.path.join(OUT, name + '.jpg')
    subprocess.run(['ffmpeg', '-v', 'error', '-ss', str(sec), '-i', SRC,
                    '-frames:v', '1', '-vf', ','.join(vf), '-q:v', str(q),
                    dst, '-y'], check=True)
    return dst


if __name__ == '__main__':
    os.makedirs(OUT, exist_ok=True)
    total = 0
    for name, sec, crop, width, q in SHOTS:
        p = grab(name, sec, crop, width, q)
        sz = os.path.getsize(p)
        total += sz
        print(f'{name:10s} {sec:7.1f}s  {sz//1024:4d} KB')
    print(f'— всего {total//1024} KB в {OUT.replace(ROOT, "")}')
