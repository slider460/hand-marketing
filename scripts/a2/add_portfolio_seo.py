def build(p):
    paras = ''.join(f'<p>{t}</p>' for t in p['paras'])
    items = ''.join(f'<li>{t}</li>' for t in p['list'])
    return (f'\n<!-- pf-seo: статичное резюме кейса для индексации (контент кейса рисует JS в #root выше) -->\n'
            f'{CSS}<section class="pf-seo" aria-label="О проекте"><div class="pf-seo__in">'
            f'<h2>{p["h2"]}</h2>{paras}'
            f'<h3>{p["list_title"]}</h3><ul>{items}</ul>'
            f'<p class="pf-links">Хотите такой же проект? Мы делаем <a href="/exhibition/">выставочные стенды под ключ</a> '
            f'и <a href="/content/">мультимедийный контент</a> — от концепции до монтажа.</p>'
            f'</div></section>\n')

total = 0
for slug, p in PAGES.items():
    for name in ('index.html', 'index-a2.html'):
        path = os.path.join(ROOT, slug, name)
        if not os.path.exists(path):
            continue
        with open(path, encoding='utf-8') as f:
            h = f.read()
        if 'pf-seo' in h:
            print(f'{slug}/{name}: уже пропатчен')
            continue
        if ANCHOR not in h:
            print(f'{slug}/{name}: нет <div id="root"></div> — пропуск')
            continue
        h = h.replace(ANCHOR, ANCHOR + build(p), 1)
        with open(path, 'w', encoding='utf-8') as f:
            f.write(h)
        total += 1
        print(f'{slug}/{name}: блок вставлен')
print('Готово, файлов:', total)
