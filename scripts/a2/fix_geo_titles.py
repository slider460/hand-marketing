#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Гео в заголовках страниц услуг и замена сокращения POSm.

По коммерческим запросам Яндекс учитывает регион, а «Москва» стояла только
в шести заголовках из восьмидесяти (замер 19.09.2026, SEO-PLAN.md). Дописываем
её там, где услуга действительно привязана к городу, и не трогаем кейсы:
у кейса в заголовке должен стоять клиент, а не гео.

Заодно «POSm» меняем на «POS-материалы»: сокращение понятно только внутри
отрасли, а в сниппете выглядит как опечатка.

    python3 scripts/a2/fix_geo_titles.py

Правит и генератор, и собранный файл, поэтому пересборка не вернёт старый текст.
"""
import glob
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))

# старый фрагмент -> новый. Меняем только в <title>, og:title и description
PAIRS = [
    ('Услуги рекламного агентства полного цикла',
     'Услуги рекламного агентства в Москве и по России'),
    ('Предметная съёмка товаров и оборудования',
     'Предметная съёмка товаров и оборудования в Москве'),
    ('Креативное агентство: айдентика и брендбуки',
     'Креативное агентство в Москве: айдентика и брендбуки'),
    ('3D mapping и проекционные шоу под ключ',
     '3D mapping и проекционные шоу под ключ в Москве'),
    ('Рекламное производство и печать: конструкции, POSm',
     'Рекламное производство и печать в Москве'),
    ('BTL-агентство: промо-акции, дегустации и сэмплинг',
     'BTL-агентство в Москве: промо-акции и сэмплинг'),
    ('Корпоративный фильм о компании: съёмка под ключ',
     'Корпоративный фильм о компании: съёмка в Москве'),
    ('Мультимедийный контент для мероприятий и выставок',
     'Мультимедийный контент для выставок и мероприятий'),
]

# сокращение из внутреннего жаргона, в выдаче читается как опечатка
WORDS = [('POSm', 'POS-материалы')]


def main():
    files = glob.glob(os.path.join(ROOT, 'mirror', '**', 'index*.html'), recursive=True) + \
        glob.glob(os.path.join(HERE, 'gen_*.py')) + \
        glob.glob(os.path.join(HERE, 'add_*.py'))
    titles = words = 0
    for f in files:
        s = open(f, encoding='utf-8').read()
        orig = s
        for old, new in PAIRS:
            if old in s:
                s = s.replace(old, new)
                titles += 1
        for old, new in WORDS:
            # «POS-материалы» уже могли поставить раньше: не трогаем то, что заменено
            n = len(re.findall(r'\bPOSm\b', s))
            if n:
                s = re.sub(r'\bPOSm\b', new, s)
                words += n
        if s != orig:
            open(f, 'w', encoding='utf-8').write(s)
            print('поправлен', f.replace(ROOT + '/', ''))
    print(f'заголовков затронуто {titles}, сокращений заменено {words}')


if __name__ == '__main__':
    main()
