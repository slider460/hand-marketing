def img(name, alt, cls='', lazy=True):
    """Кадр в родной пропорции: вертикальные снимки не режем под горизонт."""
    wh = MAP.get('sizes', {}).get(name)
    # ориентацию сохраняем, но очень вытянутые кадры мягко кадрируем,
    # иначе вертикальные снимки растягивают блок на пол-экрана
    if wh:
        k = max(0.8, min(1.9, wh[0] / wh[1]))
        ar = ' style="--ar:%.3f"' % k
    else:
        ar = ''
    return ('<picture%s><source srcset="%s/%s.jpg.webp" type="image/webp">'
            '<img src="%s/%s.jpg" alt="%s"%s%s%s></picture>'
            % (ar, IMG, name, IMG, name, alt,
               ' loading="lazy" decoding="async"' if lazy else '',
               ' class="%s"' % cls if cls else '', ar))


