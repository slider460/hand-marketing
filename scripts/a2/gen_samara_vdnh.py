def _slots():
    """Слоты расписания заново: в манифесте лежит только сводка."""
    import datetime
    import re
    import openpyxl
    out = []
    dl = os.path.expanduser('~/Downloads')
    for fn in sorted(f for f in os.listdir(dl)
                     if f.startswith('Календарь') and f.endswith('.xlsx')):
        wb = openpyxl.load_workbook(os.path.join(dl, fn), data_only=True)
        ws = wb['Календарь'] if 'Календарь' in wb.sheetnames else wb.active
        for r in ws.iter_rows(values_only=True):
            r = list(r)
            for i, c in enumerate(r):
                if isinstance(c, datetime.time) and i + 1 < len(r):
                    nxt = r[i + 1]
                    if nxt and str(nxt).strip():
                        # та же нормализация, что в scripts/samara-vdnh-assets.py,
                        # иначе имена в клетках и в списке форматов не совпадут
                        name = re.sub(r'"([^"]+)"', '«\\1»', str(nxt).strip())
                        out.append({'t': c.strftime('%H:%M'), 'e': name})
    return out


