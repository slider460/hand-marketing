#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Плитки услуг на /digital: убираем то, чего мы не делаем.

Со времён Tilda страница обещала контекстную и таргетированную рекламу, SEO,
ASO, сквозную аналитику и мобильные приложения. Владелец 19.09.2026: этих услуг
мы не оказываем и пока не планируем. Обещание чужой услуги вредит дважды:
клиент приходит не с тем запросом, а поисковик видит страницу, нерелевантную
своему же заголовку.

Меняем подписи плиток на то, что действительно делаем, длину держим близкой
к исходной: у Zero-блоков геометрия запечена в CSS, длинный текст поедет.

    python3 scripts/a2/fix_digital_tiles.py

Идемпотентен: замена идёт по точному старому тексту, повторный прогон ничего
не находит. Патчит обе копии страницы.
"""
import glob
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))

PAIRS = [
    ('Контекстная реклама', 'Посадочные страницы'),
    ('Таргетированная реклама', 'Сайты проектов'),
    ('SEO оптимизация', 'Тексты и структура'),
    ('ASO оптимизация', 'Дизайн интерфейсов'),
    ('Сквозная аналитика', 'Аналитика и цели'),
    ('Мобильные Приложения', 'Съёмка для сайта'),
    ('Оказываем полный спектр услуг по комплексному продвижению бизнеса в Интернете.',
     'Делаем сайты и посадочные страницы для проектов, которые сами придумываем и снимаем.'),
]


def main():
    files = [os.path.join(ROOT, 'mirror', 'digital', n)
             for n in ('index-a2.html', 'index.html')]
    files += glob.glob(os.path.join(HERE, 'gen_*.py'))
    total = 0
    for f in files:
        if not os.path.isfile(f):
            continue
        s = open(f, encoding='utf-8').read()
        orig, n = s, 0
        for old, new in PAIRS:
            if old in s:
                n += s.count(old)
                s = s.replace(old, new)
        if s != orig:
            open(f, 'w', encoding='utf-8').write(s)
            total += n
            print(f'{f.replace(ROOT + "/", "")}: замен {n}')
    print('всего замен:', total)


if __name__ == '__main__':
    main()
