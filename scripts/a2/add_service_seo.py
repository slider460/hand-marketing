def strip_mob(h):
    """Мобильная копия секции (.hm-seo-mob от add_seo_mobile.py). Конец ищем по
    </section></div>: внутри секции свои </div>, регулярка обрубила бы копию."""
    n = 0
    while True:
        i = h.find('<style id="hm-seo-mob-css">')
        if i < 0:
            break
        j = h.find('</section></div>', i)
        if j < 0:
            break
        h = h[:i] + h[j + len('</section></div>'):]
        n += 1
    return h, n


def strip_old(h, mark):
    """Убирает секцию прошлой сборки вместе с мобильной копией, чтобы на телефоне
    и на десктопе не оказалось двух разных текстов."""
    h, n = strip_mob(h)
    while True:
        i = h.find(f'<!-- {mark}')
        if i < 0:
            break
        j = h.find('</section>', i) + len('</section>')
        h = h[:i] + h[j:]
        n += 1
    return h, n


