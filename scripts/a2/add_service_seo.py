for slug, s in SERVICES.items():
    mark = f'sv-seo-{slug}'
    for name in ('index-a2.html', 'index.html'):
        path = os.path.join(ROOT, slug, name)
        if not os.path.exists(path):
            continue
        with open(path, encoding='utf-8') as f:
            h = f.read()
        h, rebuilt = strip_old(h, mark)
        if ANCHOR not in h:
            print(f'/{slug}/{name}: якорь формы не найден — пропуск')
            continue
        h = h.replace(ANCHOR, build(slug, s) + ANCHOR, 1)
        with open(path, 'w', encoding='utf-8') as f:
            f.write(h)
        total += 1
        print(f'/{slug}/{name}: секция {"пересобрана" if rebuilt else "вставлена"}')
print('Готово, файлов:', total)
