def part_formula(key, c):
    _, _, sh, out, fl, bag, hot, trf, car = c
    rate = sum(r for _, _, r in CREW)
    return {
        'crew': f'{pl(sh, "смена")} × {rub(rate)}',
        'kit': f'{pl(sh, "смена")} × {rub(KIT)}',
        'travel_days': f'2 дня × {rub(rate)} × {round(TRAVEL_DAY * 100)}%',
        'flights': f'{CREW_N} чел. × {rub(fl)} + перевес {rub(bag)}',
        'hotel': f'{pl(sh + 1, "ночь")} × {CREW_N} чел. × {rub(hot)}',
        'transfer': (f'аэропорт 2 × {rub(trf)} + ' if out else '') + f'{pl(sh, "день")} × {rub(car)}',
        'per_diem': f'{pl(sh + 2, "день")} × {CREW_N} чел. × {rub(PER_DIEM)}',
    }[key]


