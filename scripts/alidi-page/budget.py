def city_cost(c):
    """Разбор стоимости одной площадки. Те же формулы пишутся в Excel."""
    _, _, sh, out, fl, bag, hot, trf, car = c
    rate = sum(r for _, _, r in CREW)
    d = {
        'crew': sh * rate,
        'kit': sh * KIT,
        'travel_days': (2 * rate * TRAVEL_DAY) if out else 0,
        'flights': fl * CREW_N + bag,
        'hotel': (sh + 1) * hot * CREW_N if out else 0,
        'transfer': (2 * trf if out else 0) + sh * car,   # трансферы команды и техники: аэропорт + съёмочные дни
        'per_diem': (sh + 2) * PER_DIEM * CREW_N if out else 0,
    }
    d['total'] = sum(d.values())
    return d


