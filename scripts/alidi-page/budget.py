def _h(text, width_chars, base=15, line=12.5):
    """Высота строки под перенос текста (Excel сам не подгоняет высоту при открытии)."""
    import math
    if not text:
        return base
    per = max(int(width_chars * 1.15), 10)
    lines = sum(max(1, math.ceil(len(part) / per)) for part in str(text).split('\n'))
    return max(base, lines * line + 6)


