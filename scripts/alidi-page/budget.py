def pl(n, word):
    f = FORMS[word]
    if n % 10 == 1 and n % 100 != 11:
        return f'{n} {f[0]}'
    if n % 10 in (2, 3, 4) and n % 100 not in (12, 13, 14):
        return f'{n} {f[1]}'
    return f'{n} {f[2]}'


def tip(text):
    """Кнопка «?» с всплывающим пояснением. Открывается наведением, фокусом и тапом (page.js)."""
