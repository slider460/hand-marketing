# ---------- извлечение читаемого текста из page-JSON ----------
LABELS = {'задачи', 'задача', 'решение', 'результат', 'компания', 'цель', 'цели'}

def unwrap(t):
    """text-элемент может быть строкой, dict {'text':...} или JSON-строкой такого dict."""
    if isinstance(t, dict):
        return str(t.get('text', ''))
    if isinstance(t, str):
        s = t.strip()
        if s.startswith('{') and '"text"' in s:
            try:
                return str(json.loads(s).get('text', ''))
            except Exception:
                pass
        return t
    return json.dumps(t, ensure_ascii=False)

def clean(t):
    t = re.sub('<[^>]+>', ' ', t)
    t = re.sub(r'\s+', ' ', t).strip()
    return t

def page_data(slug):
    p = os.path.join(PAGES, slug + '.json')
    if not os.path.exists(p):
        return None
    d = json.load(open(p, encoding='utf-8'))
    seen, sentences = set(), []
    for b in d.get('blocks', []):
        for raw in b.get('texts', []):
            c = clean(unwrap(raw))
            if not c:
                continue
            low = c.lower().rstrip(':').strip()
            if low in LABELS:            # голый ярлык — пропускаем
                continue
            if len(c) < 3:
                continue
            if c in seen:
                continue
            seen.add(c)
            sentences.append(c)
    return {'meta': d.get('description', ''), 'sentences': sentences}

