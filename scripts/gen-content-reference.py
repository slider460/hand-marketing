# ---------- извлечение читаемого текста из HTML зеркала ----------
JUNK_RE = re.compile(r'^\[\{"lid"|^\{"|^&|^\W+$|^←|Hand Marketing$|\| Hand Marketing')
# навигация и кнопки, которые встречаются реже порога стоп-листа, но смысла не несут
CTA_RE = re.compile(r'^(Обсудить проект|Смотреть кейсы|Смотреть примеры|Все кейсы|Наверх|Назад к проектам)'
                    r'( Смотреть \w+| Обсудить проект)?$', re.I)

def mirror_lines(path):
    """Плоский список текстовых строк страницы без шапки, подвала, форм и скриптов."""
    if not os.path.exists(path):
        return []
    h = open(path, encoding='utf-8').read()
    h = re.sub(r'(?is)<(script|style|svg|noscript|template)[^>]*>.*?</\1>', ' ', h)
    h = re.sub(r'(?is)<(header|footer|nav|form)[^>]*>.*?</\1>', ' ', h)
    h = re.sub(r'(?is)<!--.*?-->', ' ', h)
    h = re.sub(r'(?i)<(br|/p|/div|/h[1-6]|/li|/td|/tr|/section)[^>]*>', '\n', h)
    t = html.unescape(re.sub(r'(?s)<[^>]+>', ' ', h))
    out, seen = [], set()
    for raw in t.split('\n'):
        line = re.sub(r'\s+', ' ', raw).strip()
        if len(line) < 3 or line in seen or JUNK_RE.search(line) or CTA_RE.match(line):
            continue
        seen.add(line)
        out.append(line)
    return out


def boilerplate(paths, threshold=8):
    """Строки, которые повторяются на многих страницах (cookie, реквизиты, ярлыки) — в стоп-лист."""
    cnt = collections.Counter()
    for p in paths:
        for line in set(mirror_lines(p)):
            cnt[line] += 1
    return {line for line, k in cnt.items() if k >= threshold}


# ---------- резервный источник: page-JSON ----------
LABELS = {'задачи', 'задача', 'решение', 'результат', 'компания', 'цель', 'цели'}

def unwrap(t):
    if isinstance(t, dict):
        return str(t.get('text', ''))
    if isinstance(t, str):
        s = t.strip()
        if s.startswith('{') and '"text"' in s:
            try:
                return str(json.loads(s).get('text', ''))
            except Exception:
                pass
        return t
    return json.dumps(t, ensure_ascii=False)

def page_json_lines(slug):
    p = os.path.join(PAGES, slug + '.json')
    if not os.path.exists(p):
        return []
    d = json.load(open(p, encoding='utf-8'))
    out, seen = [], set()
    for b in d.get('blocks', []):
        for raw in b.get('texts', []):
            c = re.sub(r'\s+', ' ', re.sub('<[^>]+>', ' ', unwrap(raw))).strip()
            if len(c) < 3 or c in seen or c.lower().rstrip(':').strip() in LABELS:
                continue
            seen.add(c)
            out.append(c)
    return out


def plural(n, one, few, many):
    """Русское склонение числительных: 1 кейс, 3 кейса, 54 кейса, 11 кейсов."""
    n10, n100 = n % 10, n % 100
    if 11 <= n100 <= 14:
        return many
    if n10 == 1:
        return one
    if 2 <= n10 <= 4:
        return few
    return many


def paragraph(lines, limit):
    body = re.sub(r'\s+', ' ', ' '.join(lines)).strip()
    if len(body) > limit:
        body = body[:limit].rsplit(' ', 1)[0] + '…'
    return body


